const excludedTypes = new Set(['Output', 'Image Output', 'Image']);
export function nodePickerItems(definitions, label = (type) => type) {
  const metadata = new Map(nodeCatalog.map((entry) => [entry.typeId, entry]));
  return Object.keys(definitions)
    .filter((type) => !excludedTypes.has(type))
    .map((type) => {
      const entry = metadata.get(type) || {
        typeId: type,
        categoryId: 'uncategorized',
        labelJa: '',
        aliases: [],
        description: '',
        creationRoute: 'add',
      };
      const category =
        nodeCategories.find((item) => item.id === entry.categoryId)?.label || '未分類';
      return {
        ...entry,
        id: type,
        label: label(type),
        detail: `${category} · ${entry.description}`,
      };
    });
}
const normalize = (value) => String(value).normalize('NFKC').toLowerCase();
export function searchNodeItems(items, query, categoryId = '') {
  const text = normalize(query).trim();
  const words = text.split(/\s+/).filter(Boolean);
  const rank = (item) => {
    const names = [item.typeId, item.label, item.labelJa].map(normalize);
    if (names.includes(text)) return 0;
    if (names.some((name) => name.startsWith(text))) return 1;
    if (words.every((word) => normalize(item.aliases.join(' ')).includes(word))) return 2;
    return 3;
  };
  return items
    .filter(
      (item) =>
        (!categoryId || item.categoryId === categoryId) &&
        words.every((word) =>
          normalize(
            [item.typeId, item.label, item.labelJa, ...item.aliases, item.description].join(' '),
          ).includes(word),
        ),
    )
    .sort((a, b) => (text ? rank(a) - rank(b) : 0));
}
